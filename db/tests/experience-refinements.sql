do $$declare x qa;begin select * into x from qa;
 if not exists(select 1 from public.business_intake_requests where id=x.r and message_version=1 and message_read_version=0) then raise exception 'UNREAD_MISSING';end if;
 perform public.read_intake_message(x.r,1);
 if not exists(select 1 from public.business_intake_requests where id=x.r and message_read_version=1) then raise exception 'READ_FAILED';end if;
