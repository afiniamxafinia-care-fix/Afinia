do $$declare x qa;begin select * into x from qa;
 begin perform public.submit_feedback(x.v,'stars',1,null,'Duplicate');raise exception 'TEST_DUPLICATE_ALLOWED';exception when others then if sqlerrm not like '%ALREADY_RATED%' then raise;end if;end;
 if exists(select 1 from public.public_feedback(x.b) where id=x.f) then raise exception 'PENDING_LEAK';end if;
 perform public.set_interests(array(select id from public.categories where active limit 5));
 if (select count(*) from public.user_interests where user_id=x.u)<>5 then raise exception 'INTERESTS_FAILED';end if;
 begin perform public.set_interests(array(select id from public.categories where active limit 6));raise exception 'SIX_ALLOWED';exception when others then if sqlerrm not like '%one to five%' then raise;end if;end;
end $$;
select set_config('request.jwt.claims',json_build_object('sub',a,'role','authenticated')::text,true) from qa;
do $$declare x qa;begin select * into x from qa;
 begin perform public.submit_feedback(x.v,'stars',1,null,'Attack');raise exception 'OTHER_CUSTOMER_ALLOWED';exception when others then if sqlerrm not like '%ACCESS_DENIED%' then raise;end if;end;
 perform public.moderate_feedback(x.f,'approved');
 if not exists(select 1 from public.public_feedback(x.b) where id=x.f) then raise exception 'APPROVED_MISSING';end if;
 perform public.moderate_feedback(x.f,'archived');
