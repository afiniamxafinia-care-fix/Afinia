grant all on qa to authenticated;
insert into auth.users(id,email) select u,'qa-'||u||'@example.invalid' from qa union all select a,'qa-'||a||'@example.invalid' from qa;
insert into public.platform_admins(user_id) select a from qa;
insert into public.profiles(user_id) select u from qa;
insert into public.businesses(id,slug,name,status,enrollment_status,booking_enabled,category_id) select b,'qa-'||b,'QA rollback','published','active',true,(select id from public.categories limit 1) from qa;
